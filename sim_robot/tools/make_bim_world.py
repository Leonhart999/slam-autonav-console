#!/usr/bin/env python3
"""Build a Gazebo world from a region of one SLABIM storey (HKUST main building BIM).

Source: SLABIM dataset (Huang et al., ICRA 2025), BIM/<storey>/mesh/{walls,columns}.ply,
downloaded from https://huggingface.co/datasets/BobH62/SLABIM (cite the paper when used).

What it does
  1. read walls + columns of one storey, keep triangles whose centroid lies in the chosen box
     (BIM coordinates, metres) and whose height range overlaps [z_min, z_max]
  2. door leaves are left out on purpose, so every doorway is open (rooms are reachable)
  3. shift the region so its centre is the world origin and the storey floor is at z = 0
  4. write one binary STL (used for both visual and collision) as model models/bim_<name>/
     and a world worlds/<name>.sdf with the same plugins as the other scenes + sim_robot

Usage
  python3 make_bim_world.py --slabim /path/to/SLABIM --storey 4F --box -35 60 -25 35 \
      --name hkust_4f_west --start 0 0 0          # robot start in BIM coordinates (x y yaw)
  The dataset folder can also be given with the environment variable SLABIM_DIR.
"""
import argparse
import os
import struct
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ply_info import read_ply  # noqa: E402

PKG = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def write_stl(path, tris):
    tris = tris.astype(np.float32)
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-12
    rec = np.zeros(len(tris), dtype=[('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')])
    rec['n'], rec['v'] = n, tris
    with open(path, 'wb') as f:
        f.write(b'bim region'.ljust(80, b'\0'))
        f.write(struct.pack('<I', len(tris)))
        f.write(rec.tobytes())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--slabim', default=os.environ.get('SLABIM_DIR'),
                    help='SLABIM dataset folder (contains BIM/<storey>/mesh); default $SLABIM_DIR')
    ap.add_argument('--storey', default='4F')
    ap.add_argument('--box', nargs=4, type=float, required=True, metavar=('XMIN', 'XMAX', 'YMIN', 'YMAX'))
    ap.add_argument('--name', required=True)
    ap.add_argument('--zmin', type=float, default=-0.5)
    ap.add_argument('--zmax', type=float, default=4.0, help='drop geometry starting above this height')
    ap.add_argument('--start', nargs=3, type=float, default=None, metavar=('X', 'Y', 'YAW'),
                    help='robot start in BIM coordinates; default = box centre, yaw 0')
    ap.add_argument('--ceiling', type=float, default=0.0,
                    help='height of a flat ceiling over the region (0 = none). Without a ceiling the '
                         'vertical direction is barely constrained in narrow corridors and FAST-LIO '
                         'drifts in z (measured +0.4 m in the first run)')
    ap.add_argument('--model-only', action='store_true',
                    help='write only models/bim_<name>/ (keep the shipped world file, e.g. when rebuilding the '
                         'model from your own SLABIM download)')
    args = ap.parse_args()
    if not args.slabim:
        ap.error('give the SLABIM dataset folder with --slabim or the environment variable SLABIM_DIR')
    SLABIM = args.slabim
    x0, x1, y0, y1 = args.box
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2

    parts = []
    for part in ('walls', 'columns'):
        v, t = read_ply(f'{SLABIM}/BIM/{args.storey}/mesh/{part}.ply')
        tri = v[t]
        c = tri.mean(1)
        zlo, zhi = tri[:, :, 2].min(1), tri[:, :, 2].max(1)
        keep = (c[:, 0] > x0) & (c[:, 0] < x1) & (c[:, 1] > y0) & (c[:, 1] < y1) \
            & (zhi > args.zmin) & (zlo < args.zmax)
        parts.append(tri[keep])
        print(f'{part:8s}: kept {keep.sum():7d} of {len(tri):7d} triangles')
    tri = np.concatenate(parts)
    tri[:, :, 0] -= cx
    tri[:, :, 1] -= cy

    model_dir = os.path.join(PKG, 'models', f'bim_{args.name}')
    os.makedirs(os.path.join(model_dir, 'meshes'), exist_ok=True)
    write_stl(os.path.join(model_dir, 'meshes', 'building.stl'), tri)
    with open(os.path.join(model_dir, 'model.config'), 'w') as f:
        f.write(f'<?xml version="1.0"?>\n<model><name>bim_{args.name}</name><version>1.0</version>'
                f'<sdf version="1.8">model.sdf</sdf><description>SLABIM {args.storey} region '
                f'x[{x0},{x1}] y[{y0},{y1}] (BIM coords), walls + columns, doors removed</description></model>\n')
    with open(os.path.join(model_dir, 'model.sdf'), 'w') as f:
        f.write(f'''<?xml version="1.0"?>
<!-- generated by tools/make_bim_world.py; SLABIM {args.storey}, BIM region x[{x0},{x1}] y[{y0},{y1}],
     shifted by (-{cx}, -{cy}) so the region centre is the origin -->
<sdf version="1.8">
  <model name="bim_{args.name}">
    <static>true</static>
    <link name="link">
      <collision name="collision"><geometry><mesh><uri>meshes/building.stl</uri></mesh></geometry></collision>
      <visual name="visual"><geometry><mesh><uri>meshes/building.stl</uri></mesh></geometry>
        <material><ambient>0.8 0.8 0.78 1</ambient><diffuse>0.8 0.8 0.78 1</diffuse></material></visual>
    </link>
  </model>
</sdf>
''')

    if args.model_only:
        print(f'model -> {model_dir} (world file not written: --model-only)')
        return
    if args.start is None:
        sx, sy, syaw = 0.0, 0.0, 0.0
    else:
        sx, sy, syaw = args.start[0] - cx, args.start[1] - cy, args.start[2]
    ceiling = ''
    if args.ceiling > 0:
        sx_box, sy_box = x1 - x0, y1 - y0
        g = f'<box><size>{sx_box} {sy_box} 0.1</size></box>'
        ceiling = (f'    <model name="ceiling"><static>true</static><pose>0 0 {args.ceiling + 0.05} 0 0 0</pose>\n'
                   f'      <link name="link"><collision name="c"><geometry>{g}</geometry></collision>\n'
                   f'        <visual name="v"><geometry>{g}</geometry><material><ambient>0.9 0.9 0.9 1</ambient>'
                   f'<diffuse>0.9 0.9 0.9 1</diffuse></material></visual></link></model>')
    world = f'''<?xml version="1.0"?>
<!-- generated by tools/make_bim_world.py; building geometry from the SLABIM dataset (HKUST main building BIM) -->
<sdf version="1.8">
  <world name="{args.name}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-imu-system" name="ignition::gazebo::systems::Imu"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows><pose>0 0 20 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><direction>-0.3 0.2 -1</direction>
    </light>
    <model name="ground"><static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>300 300</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>300 300</size></plane></geometry>
          <material><ambient>0.55 0.55 0.55 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse></material></visual>
      </link></model>
    <include><uri>model://bim_{args.name}</uri></include>
{ceiling}
    <include>
      <uri>model://sim_robot</uri>
      <pose>{sx:.3f} {sy:.3f} 0.1 0 0 {syaw:.4f}</pose>
    </include>
  </world>
</sdf>
'''
    out = os.path.join(PKG, 'worlds', f'{args.name}.sdf')
    with open(out, 'w') as f:
        f.write(world)
    print(f'{len(tri)} triangles -> {model_dir}/meshes/building.stl')
    print(f'world -> {os.path.normpath(out)}; robot start (world) {sx:.2f} {sy:.2f} yaw {syaw:.2f}')
    print(f'BIM -> world: subtract ({cx}, {cy})')


if __name__ == '__main__':
    main()
