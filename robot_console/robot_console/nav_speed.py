"""Navigation speed multiplier.

Why not just change Nav2 parameters at runtime: in this Nav2 (Humble) setting FollowPath.max_vel_x through the
parameter service is accepted but DWB keeps driving at the yaml limit (tested 2026-11-04: max_vel_x set to 1.5,
controller output still peaked at 0.47 m/s). The /speed_limit topic, Nav2's official runtime limit, does work.

So the console starts Nav2 with a derived params file whose limits are the *top* speed (base x max multiplier),
and publishes /speed_limit = base speed x chosen multiplier. The original lidar_nav yaml is not modified, so
command-line experiments keep the baseline values.
"""
import os

import yaml


def write_console_params(src, dst, scale_max, cap_w):
    """Copy src with the DWB and velocity_smoother limits raised to base x scale_max.

    Returns (base_v, base_w): the 1x linear / angular limits read from src.
    DWB scales max_vel_theta with the same ratio as the speed limit, so its top value is base_w x scale_max;
    the velocity smoother still caps the angular speed at cap_w.
    """
    with open(src, encoding='utf-8') as f:
        params = yaml.safe_load(f)
    follow = params['controller_server']['ros__parameters']['FollowPath']
    smoother = params['velocity_smoother']['ros__parameters']
    base_v = float(follow['max_vel_x'])
    base_w = float(follow['max_vel_theta'])
    top_v = round(base_v * scale_max, 3)
    follow['max_vel_x'] = top_v
    follow['max_speed_xy'] = round(float(follow['max_speed_xy']) * scale_max, 3)
    follow['max_vel_theta'] = round(base_w * scale_max, 3)
    top_w = min(base_w * scale_max, cap_w)
    smoother['max_velocity'] = [top_v, 0.0, top_w]
    smoother['min_velocity'] = [-top_v, 0.0, -top_w]
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(f'# Generated by robot_console from {src}; do not edit (see robot_console/nav_speed.py)\n')
        yaml.safe_dump(params, f, sort_keys=False)
    os.replace(tmp, dst)
    return base_v, base_w
